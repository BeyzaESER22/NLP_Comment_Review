def categorize_errors(data, y_true, y_pred):
    rows = []
    for item, gold, pred in zip(data, y_true, y_pred):
        g = {(s, e): t for t, s, e in get_entities(gold)}
        p = {(s, e): t for t, s, e in get_entities(pred)}
        text = " ".join(item["words"])

        for (s, e), t in g.items():
            if (s, e) in p:
                if p[(s, e)] != t:
                    rows.append(("polarity" if t.startswith("ASP") and p[(s, e)].startswith("ASP") else "type", t, p[(s, e)], text))
            elif any(ps <= e and pe >= s for ps, pe in p):
                rows.append(("boundary", t, "overlap", text))
            else:
                rows.append(("missed", t, "-", text))

        for (s, e), t in p.items():
            if (s, e) not in g and not any(gs <= e and ge >= s for gs, ge in g):
                rows.append(("spurious", "-", t, text))
    return pd.DataFrame(rows, columns=["error_type", "gold", "pred", "sentence"])


