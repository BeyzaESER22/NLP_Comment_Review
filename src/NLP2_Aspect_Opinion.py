class SequenceTaggingDataset(Dataset):
    def __init__(self, data, word2idx, pos2idx, tag2idx):
        self.data = data
        self.word2idx = word2idx
        self.pos2idx = pos2idx
        self.tag2idx = tag2idx

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        item = self.data[idx]
        w_ids = [self.word2idx.get(w.lower(), self.word2idx['<UNK>']) for w in item['words']]
        p_ids = [self.pos2idx.get(p, self.pos2idx['<UNK>']) for p in item['pos_tags']]
        t_ids = [self.tag2idx[t] for t in item['bio_tags']]
        return torch.tensor(w_ids), torch.tensor(p_ids), torch.tensor(t_ids)

def pad_collate_fn(batch):
    w_graphs, p_graphs, t_graphs = zip(*batch)
    lens = [len(x) for x in w_graphs]
    max_len = max(lens)

    w_padded = torch.zeros(len(batch), max_len, dtype=torch.long)
    p_padded = torch.zeros(len(batch), max_len, dtype=torch.long)
    t_padded = torch.zeros(len(batch), max_len, dtype=torch.long)
    mask = torch.zeros(len(batch), max_len, dtype=torch.bool)

    for i, (w, p, t) in enumerate(zip(w_graphs, p_graphs, t_graphs)):
        l = len(w)
        w_padded[i, :l] = w
        p_padded[i, :l] = p
        t_padded[i, :l] = t
        mask[i, :l] = True

    return w_padded, p_padded, t_padded, mask

class BiLSTM_CRF(nn.Module):
    def __init__(self, vocab_size, pos_size, num_tags, emb_dim=100, pos_dim=25, hidden_dim=256):
        super().__init__()
        self.word_embeds = nn.Embedding(vocab_size, emb_dim, padding_idx=0)
        self.pos_embeds = nn.Embedding(pos_size, pos_dim, padding_idx=0)
        self.dropout = nn.Dropout(0.5)
        self.lstm = nn.LSTM(emb_dim + pos_dim, hidden_dim // 2, num_layers=1,
                            bidirectional=True, batch_first=True)
        self.hidden2tag = nn.Linear(hidden_dim, num_tags)
        self.crf = CRF(num_tags, batch_first=True)

    def _get_lstm_features(self, words, pos_tags):
        embeds = torch.cat([self.word_embeds(words), self.pos_embeds(pos_tags)], dim=-1)
        embeds = self.dropout(embeds)
        lstm_out, _ = self.lstm(embeds)
        lstm_out = self.dropout(lstm_out)
        return self.hidden2tag(lstm_out)

    def forward_loss(self, words, pos_tags, tags, mask):
        feats = self._get_lstm_features(words, pos_tags)
        return -self.crf(feats, tags, mask=mask, reduction='mean')

    def decode(self, words, pos_tags, mask):
        feats = self._get_lstm_features(words, pos_tags)
        return self.crf.decode(feats, mask=mask)

