def extract_structured_triplets(dataset, predictions):
    """1. INFORMATION EXTRACTION: BIO predictions -> (Aspect, Opinion, Polarity) records.
    Each aspect is paired with the nearest opinion span in the sentence."""
    extracted_records = []
    for item, tags in zip(dataset, predictions):
        words, sent_id = item['words'], item['id']
        aspects, opinions = [], []          # (text, polarity, position) / (text, position)

        i = 0
        while i < len(words):
            tag = tags[i]
            if tag.startswith('B-ASP_'):
                polarity, start = tag.split('_')[-1], i
                span = [words[i]]
                i += 1
                while i < len(words) and tags[i].startswith('I-ASP_'):
                    span.append(words[i]); i += 1
                clean = re.sub(r'[^\w\s]', '', " ".join(span)).strip().lower()
                if clean:
                    aspects.append((clean, polarity, start))
            elif tag.startswith('B-OPINION'):
                start = i
                span = [words[i]]
                i += 1
                while i < len(words) and tags[i].startswith('I-OPINION'):
                    span.append(words[i]); i += 1
                clean = re.sub(r'[^\w\s]', '', " ".join(span)).strip().lower()
                if clean:
                    opinions.append((clean, start))
            else:
                i += 1

        for asp_term, pol, asp_pos in aspects:
            if opinions:
                opinion_str = min(opinions, key=lambda o: abs(o[1] - asp_pos))[0]
            else:
                opinion_str = "implicit_opinion"
            extracted_records.append({
                'Sentence_ID': sent_id,
                'Aspect_Entity': asp_term,
                'Subjective_Opinion': opinion_str,
                'Polarity': pol,
                'Review_Snippet': " ".join(words),
            })
    return pd.DataFrame(extracted_records, columns=['Sentence_ID', 'Aspect_Entity',
                                                    'Subjective_Opinion', 'Polarity', 'Review_Snippet'])


