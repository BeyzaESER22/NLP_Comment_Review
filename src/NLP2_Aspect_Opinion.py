def token_features(words, pos_tags, i):
    w, pos = words[i], pos_tags[i]
    feats = {
        'bias': 1.0,
        'word.lower': w.lower(),
        'word[-3:]': w[-3:],
        'word[-2:]': w[-2:],
        'word[:3]': w[:3],
        'word.isupper': w.isupper(),
        'word.istitle': w.istitle(),
        'word.isdigit': w.isdigit(),
        'pos': pos,
        'pos[:2]': pos[:2],
    }
    for off in (-2, -1, 1, 2):
        j = i + off
        if 0 <= j < len(words):
            feats[f'{off}:word.lower'] = words[j].lower()
            feats[f'{off}:pos'] = pos_tags[j]
        else:
            feats[f'{off}:{"BOS" if off < 0 else "EOS"}'] = True
    return feats

