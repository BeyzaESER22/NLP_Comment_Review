class HMMSequenceTagger:
    def __init__(self, unk_threshold=1, smoothing=0.01, use_pos=True):
        self.unk_threshold = unk_threshold
        self.smoothing = smoothing
        self.use_pos = use_pos

    def _obs(self, word, pos):
        w = word.lower()
        if w in self.vocab:
            return w
        return f'<UNK>_{pos}' if self.use_pos else '<UNK>'

    def fit(self, data, target_key='bio_tags'):
        counts = Counter(w.lower() for item in data for w in item['words'])
        self.vocab = {w for w, c in counts.items() if c > self.unk_threshold}

        seqs = [([self._obs(w, p) for w, p in zip(it['words'], it['pos_tags'])], it[target_key])
                for it in data if it[target_key]]

        self.tags = sorted({t for _, ts in seqs for t in ts})
        self.symbols = sorted({o for obs, _ in seqs for o in obs})
        self.tag2i = {t: i for i, t in enumerate(self.tags)}
        self.sym2i = {s: i for i, s in enumerate(self.symbols)}
        T, V = len(self.tags), len(self.symbols)

        start = np.zeros(T)
        trans = np.zeros((T, T))
        emit = np.zeros((T, V))
        for obs, tags in seqs:
            start[self.tag2i[tags[0]]] += 1
            for i, (o, t) in enumerate(zip(obs, tags)):
                emit[self.tag2i[t], self.sym2i[o]] += 1
                if i > 0:
                    trans[self.tag2i[tags[i - 1]], self.tag2i[t]] += 1

        k = self.smoothing
        self.log_start = np.log((start + k) / (start.sum() + k * T))
        self.log_trans = np.log((trans + k) / (trans.sum(1, keepdims=True) + k * T))
        # V + 1 reserves a little probability mass for symbols never seen in training
        self.log_emit = np.log((emit + k) / (emit.sum(1, keepdims=True) + k * (V + 1)))
        self.log_unseen = np.log(k / (emit.sum(1) + k * (V + 1)))

    def _emission_matrix(self, words, pos_tags):
        cols = []
        for w, p in zip(words, pos_tags):
            j = self.sym2i.get(self._obs(w, p))
            cols.append(self.log_emit[:, j] if j is not None else self.log_unseen)
        return np.stack(cols, axis=1)           # tags x words

    def viterbi_decode(self, words, pos_tags, return_trellis=False):
        em = self._emission_matrix(words, pos_tags)
        T, n = em.shape
        viterbi = np.zeros((T, n))
        backpointer = np.zeros((T, n), dtype=int)

        viterbi[:, 0] = self.log_start + em[:, 0]
        for t in range(1, n):
            scores = viterbi[:, t - 1][:, None] + self.log_trans    # prev x curr
            backpointer[:, t] = scores.argmax(axis=0)
            viterbi[:, t] = scores.max(axis=0) + em[:, t]

        best = int(viterbi[:, -1].argmax())
        path = [best]
        for t in range(n - 1, 0, -1):
            best = int(backpointer[best, t])
            path.append(best)
        path.reverse()

        decoded = [self.tags[i] for i in path]
        if return_trellis:
            return decoded, pd.DataFrame(viterbi, index=self.tags, columns=words)
        return decoded, None

    def predict(self, data):
        return [self.viterbi_decode(it['words'], it['pos_tags'])[0] for it in data]


