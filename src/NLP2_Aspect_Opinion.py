MODEL_NAME = 'bert-base-uncased'
bert_device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

labels = sorted({t for s in full_dataset for t in s['bio_tags']})
l2i = {l: i for i, l in enumerate(labels)}
i2l = {i: l for l, i in l2i.items()}

tok = AutoTokenizer.from_pretrained(MODEL_NAME)


def encode(data, max_len=128):
    enc = tok([s['words'] for s in data], is_split_into_words=True,
              truncation=True, max_length=max_len, padding=True, return_tensors='pt')
    lab = torch.full(enc['input_ids'].shape, -100, dtype=torch.long)
    first_idx = []
    for i, s in enumerate(data):
        prev, idxs = None, []
        for j, wid in enumerate(enc.word_ids(i)):
            if wid is None:
                continue
            if wid != prev:
                lab[i, j] = l2i[s['bio_tags'][wid]]
                idxs.append(j)
            prev = wid
        first_idx.append(idxs)
    return enc, lab, first_idx


def predict_bert(model, data):
    enc, _, first_idx = encode(data)
    loader = DataLoader(TensorDataset(enc['input_ids'], enc['attention_mask']), batch_size=64)
    model.eval()
    chunks = []
    with torch.no_grad():
        for ids, mask in loader:
            logits = model(input_ids=ids.to(bert_device), attention_mask=mask.to(bert_device)).logits
            chunks.append(logits.argmax(-1).cpu())
    pred_ids = torch.cat(chunks)
    out = []
    for i, s in enumerate(data):
        p = [i2l[int(pred_ids[i, j])] for j in first_idx[i]]
        p += ['O'] * (len(s['words']) - len(p))   # kesilen kelimeler icin
        out.append(p)
    return out


