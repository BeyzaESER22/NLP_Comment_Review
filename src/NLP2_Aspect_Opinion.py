def plot_opinion_knowledge_graph(ie_df, max_relations=15):
    """3. KNOWLEDGE GRAPH: Domain -> Aspect -> Opinion, edges colored by polarity."""
    valid_df = ie_df[ie_df['Subjective_Opinion'] != 'implicit_opinion'].head(max_relations)
    if valid_df.empty:
        print("Knowledge graph için açık (explicit) opinion içeren kayıt bulunamadı.")
        return

    G = nx.DiGraph()
    root_node = "Product / Venue"
    G.add_node(root_node, node_type='root')

    for _, row in valid_df.iterrows():
        aspect = f"ASP: {row['Aspect_Entity']}"
        opinion = f"OP: {row['Subjective_Opinion'].split(',')[0].strip()}"
        pol = row['Polarity']
        G.add_node(aspect, node_type='aspect')
        G.add_node(opinion, node_type='opinion')
        G.add_edge(root_node, aspect, relation='HAS_ASPECT', color='gray')
        G.add_edge(aspect, opinion, relation=f"RATED_{pol}",
                   color='green' if pol == 'POS' else ('red' if pol == 'NEG' else 'orange'))

    plt.figure(figsize=(13, 8))
    pos = nx.spring_layout(G, k=0.9, seed=SEED)
    palette = {'root': '#FFD700', 'aspect': '#87CEEB', 'opinion': '#98FB98'}
    node_colors = [palette.get(G.nodes[n].get('node_type'), '#DDDDDD') for n in G.nodes()]
    edge_colors = [d.get('color', 'gray') for _, _, d in G.edges(data=True)]

